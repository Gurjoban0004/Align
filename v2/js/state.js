/**
 * Active calorie burn estimate.
 */
export function getActiveBurn(day) {
  if (day && typeof day.activeBurn === 'number' && day.activeBurn > 0) {
    return Math.round(day.activeBurn);
  }
  let burn = 0;
  if (day?.steps > 0) burn += day.steps * 0.04;
  if (day?.workouts?.length > 0) {
    const totalSets = day.workouts.reduce((acc, ex) => acc + (parseInt(ex.sets) || 0), 0);
    burn += 150 + (totalSets * 20);
  }
  return Math.round(burn);
}

/**
 * Compute daily score (0-100).
 */
export function computeDailyScore(day) {
  const profile = _state.profile || {};
  const habits = _state.habits || [];

  const stepGoal = profile.targetSteps || 10000;
  const calGoal = profile.targetCalories || 2000;
  const sleepGoal = profile.targetSleep || 8;
  const waterGoal = profile.targetWater || 8;

  const stepScore = Math.min(100, ((day.steps || 0) / stepGoal) * 100);
  const sleepScore = Math.min(100, ((day.sleep || 0) / sleepGoal) * 100);
  const waterScore = Math.min(100, ((day.water || 0) / waterGoal) * 100);

  const netCals = Math.max(0, (day.calories || 0) - getActiveBurn(day));
  const calScore = calGoal > 0 ? Math.min(100, (netCals / calGoal) * 100) : 50;

  const habitCount = habits.length || 1;
  const completedCount = (day.habitsCompleted || []).length;
  const habitScore = Math.min(100, (completedCount / habitCount) * 100);

  return Math.round((stepScore + sleepScore + waterScore + calScore + habitScore) / 5);
}

/**
 * Get 7-day average trends.
 */
export function getWeeklyTrends(baseDateStr) {
  const baseDate = new Date(baseDateStr || _state.dateStr);
  let stepsSum = 0, stepsN = 0;
  let sleepSum = 0, sleepN = 0;
  let calSum = 0, calN = 0;
  const weights = [];

  for (let i = 0; i < 7; i++) {
    const d = new Date(baseDate);
    d.setDate(baseDate.getDate() - i);
    const key = d.toISOString().split('T')[0];
    const day = _state.logs[key];
    if (!day) continue;

    if (day.steps > 0) { stepsSum += day.steps; stepsN++; }
    if (day.sleep > 0) { sleepSum += day.sleep; sleepN++; }
    if (day.calories > 0) { calSum += day.calories; calN++; }
    if (day.weight > 0) weights.push({ date: key, weight: day.weight });
  }

  weights.sort((a, b) => a.date.localeCompare(b.date));
  let weightChange = 0;
  if (weights.length >= 2) {
    weightChange = weights[weights.length - 1].weight - weights[0].weight;
  }

  return {
    avgSteps: stepsN > 0 ? Math.round(stepsSum / stepsN) : 0,
    avgSleep: sleepN > 0 ? parseFloat((sleepSum / sleepN).toFixed(1)) : 0,
    avgCalories: calN > 0 ? Math.round(calSum / calN) : 0,
    weightChange: parseFloat(weightChange.toFixed(1)),
    latestWeight: weights.length > 0 ? weights[weights.length - 1].weight : null,
  };
}

// ─── Time Period Detection ───

export function detectTimePeriod() {
  const hour = new Date().getHours();
  if (hour >= 5 && hour < 10) return 'morning';
  if (hour >= 10 && hour < 16) return 'midday';
  if (hour >= 16 && hour < 21) return 'evening';
  return 'night';
}

export function getGreeting() {
  const name = _state.profile?.name || '';
  const firstName = name.split(' ')[0] || '';
  const period = _state.timePeriod;

  const greetings = {
    morning: firstName ? `Good morning, ${firstName}` : 'Good morning',
    midday: firstName ? `Hey ${firstName}` : 'Good afternoon',
    evening: firstName ? `Evening, ${firstName}` : 'Good evening',
    night: firstName ? `Wind down, ${firstName}` : 'Night mode',
  };

  return greetings[period] || greetings.morning;
}

