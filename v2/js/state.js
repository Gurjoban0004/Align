// ─── State Container ───

let _state = {};
const _subscribers = {};     // key → Set<callback>
const _globalSubs = new Set(); // called on any change

/**
 * Initialize state from localStorage + defaults.
 */
export function initState() {
  _state = { ...DEFAULT_STATE };

  // Restore persisted keys
  const persistedKeys = [
    'profile', 'logs', 'workoutSplits', 'recipes',
    'habits', 'books', 'movies', 'userModel', 'insightQueue',
    'personalRecords',
  ];

  for (const key of persistedKeys) {
    const stored = localStorage.getItem(LS_PREFIX + key);
    if (stored) {
      try {
        _state[key] = JSON.parse(stored);
      } catch (e) {
        console.warn(`Failed to parse stored ${key}:`, e);
      }
    }
  }

  // Detect time period
  _state.timePeriod = detectTimePeriod();

  // Check for plaintext keys in profile, migrate to sessionStorage, and scrub from localStorage
  if (_state.profile) {
    let updated = false;
    if (_state.profile.geminiApiKey) {
      setGeminiKey(_state.profile.geminiApiKey);
      delete _state.profile.geminiApiKey;
      _state.profile.hasGeminiKey = true;
      updated = true;
    }
    if (_state.profile.omdbApiKey) {
      setOmdbKey(_state.profile.omdbApiKey);
      delete _state.profile.omdbApiKey;
      _state.profile.hasOmdbKey = true;
      updated = true;
    }
    if (updated) {
      localStorage.setItem(LS_PREFIX + 'profile', JSON.stringify(_state.profile));
    }
  }

  // 1c. Bidirectionally sync habits and logs immediately on init
  syncAllHabitsAndLogs();
}

let _isSyncing = false;
export function syncAllHabitsAndLogs() {
  if (_isSyncing) return;
  _isSyncing = true;
  try {
    const habits = _state.habits || [];
    const logs = _state.logs || {};
    let logsUpdated = false;
    let habitsUpdated = false;

    // 1. Ensure dates in completions are in logs
    const newHabits = habits.map(h => {
      const completionsSet = new Set(h.completions || []);
      const originalSize = completionsSet.size;

      completionsSet.forEach(dateStr => {
        if (!logs[dateStr]) {
          logs[dateStr] = getEmptyDayLog();
          logsUpdated = true;
        }
        if (!logs[dateStr].habitsCompleted) {
          logs[dateStr].habitsCompleted = [];
          logsUpdated = true;
        }
        if (!logs[dateStr].habitsCompleted.includes(h.id)) {
          logs[dateStr].habitsCompleted.push(h.id);
          logsUpdated = true;
        }
      });

      // 2. Ensure dates in logs are in completions
      Object.keys(logs).forEach(dateStr => {
        const day = logs[dateStr];
        if (day && day.habitsCompleted && day.habitsCompleted.includes(h.id)) {
          if (!completionsSet.has(dateStr)) {
            completionsSet.add(dateStr);
            habitsUpdated = true;
          }
        }
      });

      if (completionsSet.size !== originalSize) {
        habitsUpdated = true;
      }
      return { ...h, completions: Array.from(completionsSet) };
    });

    // 3. Prune orphaned habit IDs from logs
    const activeHabitIds = new Set(habits.map(h => h.id));
    Object.keys(logs).forEach(dateStr => {
      const day = logs[dateStr];
      if (day && day.habitsCompleted) {
        const filtered = day.habitsCompleted.filter(id => activeHabitIds.has(id));
        if (filtered.length !== day.habitsCompleted.length) {
          day.habitsCompleted = filtered;
          logsUpdated = true;
        }
      }
    });

    if (logsUpdated) {
      setState('logs', { ...logs });
    }
    if (habitsUpdated) {
      setState('habits', newHabits);
    }
  } finally {
    _isSyncing = false;
  }
}

/**
 * Get a state value.
 */
export function getState(key) {
  if (key === undefined) return { ..._state };
  return _state[key];
}

/**
 * Set a state value and notify subscribers.
 */
export function setState(key, value) {
  const prev = _state[key];
  _state[key] = value;

  // Persist if it's a persistable key
  const persistedKeys = [
    'profile', 'logs', 'workoutSplits', 'recipes',
    'habits', 'books', 'movies', 'userModel', 'insightQueue',
    'personalRecords',
  ];
  if (persistedKeys.includes(key)) {
    try {
      localStorage.setItem(LS_PREFIX + key, JSON.stringify(value));
    } catch (e) {
      console.warn(`Failed to persist ${key}:`, e);
    }
  }

  // Notify key-specific subscribers
  if (_subscribers[key]) {
    for (const cb of _subscribers[key]) {
      try { cb(value, prev, key); } catch (e) { console.error('Subscriber error:', e); }
    }
  }

  // Notify global subscribers
  for (const cb of _globalSubs) {
    try { cb(key, value, prev); } catch (e) { console.error('Global subscriber error:', e); }
  }

  // Auto-sync logs/habits when habits or logs change
  if (key === 'habits' || key === 'logs') {
    syncAllHabitsAndLogs();
  }
}

/**
 * Subscribe to changes on a specific key.
 * Returns an unsubscribe function.
 */
export function subscribe(key, callback) {
  if (!_subscribers[key]) _subscribers[key] = new Set();
  _subscribers[key].add(callback);
  return () => _subscribers[key].delete(callback);
}

/**
 * Subscribe to any state change.
 */
export function subscribeAll(callback) {
  _globalSubs.add(callback);
  return () => _globalSubs.delete(callback);
}

// ─── Day Log Helpers ───

/**
 * Get today's log (creates if needed).
 */
export function getDayLog(dateStr) {
  const d = dateStr || _state.dateStr;
  const logs = _state.logs;

  if (!logs[d]) {
    logs[d] = getEmptyDayLog();
    setState('logs', { ...logs });
  }

  // Normalize — fill in missing fields
  const day = logs[d];
  const defaults = getEmptyDayLog();
  for (const key in defaults) {
    if (day[key] === undefined || day[key] === null) {
      day[key] = defaults[key];
    }
  }

  return day;
}

/**
 * Update a field in today's log and persist.
 */
export function updateDayLog(dateStr, updates) {
  const d = dateStr || _state.dateStr;
  const day = getDayLog(d);

  Object.assign(day, updates);

  // Auto-sync habits based on metric goals
  syncAutoHabits(day);

  const logs = { ..._state.logs, [d]: day };
  setState('logs', logs);

  // Sync completions
  syncAllHabitsAndLogs();
}

/**
 * Sync habits that auto-complete based on metrics.
 */
function syncAutoHabits(day) {
  if (!day.habitsCompleted) day.habitsCompleted = [];
  const profile = _state.profile || {};

  const stepGoal = profile.targetSteps || 10000;
  const waterGoal = profile.targetWater || 8;

  // Reading habit (h1)
  const hasReadHabit = day.habitsCompleted.includes('h1');
  const targetPages = 15;
  if (day.pagesRead >= targetPages && !hasReadHabit) {
    day.habitsCompleted.push('h1');
  } else if (day.pagesRead < targetPages && hasReadHabit) {
    day.habitsCompleted = day.habitsCompleted.filter(id => id !== 'h1');
  }

  // Steps habit (h2)
  const hasStepHabit = day.habitsCompleted.includes('h2');
  if (day.steps >= stepGoal && !hasStepHabit) {
    day.habitsCompleted.push('h2');
  } else if (day.steps < stepGoal && hasStepHabit) {
    day.habitsCompleted = day.habitsCompleted.filter(id => id !== 'h2');
  }

  // Water habit (h3)
  const hasWaterHabit = day.habitsCompleted.includes('h3');
  if (day.water >= waterGoal && !hasWaterHabit) {
    day.habitsCompleted.push('h3');
  } else if (day.water < waterGoal && hasWaterHabit) {
    day.habitsCompleted = day.habitsCompleted.filter(id => id !== 'h3');
  }
}

